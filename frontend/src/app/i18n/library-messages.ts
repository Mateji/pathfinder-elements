export function issueDescription(
    fields: Readonly<Record<string, string>>, errors: Readonly<Record<string, string | undefined> & { invalid: string }>,
    path: string, code: string
): string {
    const fieldPath = path.split('.').map((segment) => {
        const match = /^(\w+)(?:\[(\d+)\])?$/.exec(segment);
        const field = match ? fields[match[1]] : undefined;
        if (!field) {
            return segment;
        }
        return match?.[2] === undefined ? field : `${field} ${Number(match[2]) + 1}`;
    }).join(' › ');
    return `${fieldPath} – ${errors[code] ?? errors.invalid}`;
}
